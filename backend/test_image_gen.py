async def run_campaign(brand: BrandCore, goal: CampaignGoal, image_provider: str, image_api_key: str = None) -> ListType[GeneratedPost]:
    """Full campaign generation - DeepSeek does ALL the creative work"""
    
    print("\n" + "="*70)
    print("  🧠 DEEPSEEK - CREATIVE DIRECTOR MODE")
    print("="*70)
    
    # Step 1: Research and understand the company
    print("\n📊 [1/5] Analyzing brand and campaign context...")
