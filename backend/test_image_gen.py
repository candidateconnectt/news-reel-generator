def hex_to_rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))


def get_font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    candidates_bold = [
        "C:/Windows/Fonts/Inter-Bold.ttf", "C:/Windows/Fonts/arialbd.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    ]
    candidates_regular = [
        "C:/Windows/Fonts/Inter-Regular.ttf", "C:/Windows/Fonts/arial.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ]
    candidates = candidates_bold if bold else candidates_regular
    for path in candidates:
        try:
            return ImageFont.truetype(path, size)
        except (IOError, OSError):
            continue
    return ImageFont.load_default()


def render_professional_post(
    bg_bytes: bytes,
    post: GeneratedPost,
    brand: BrandCore,
    layout_strategy: str,
    bible: dict,
    out_path: Path,
    canvas_size: int = 1080,
) -> Path:
    """Render final post with consistent brand elements"""
    
    # Load background from bytes
    from io import BytesIO
    bg = Image.open(BytesIO(bg_bytes)).convert("RGBA")
    bg = bg.resize((canvas_size, canvas_size), Image.LANCZOS)
    
    primary_rgb = hex_to_rgb(brand.primary_color)
    accent_rgb = hex_to_rgb(brand.accent_color)
    white = hex_to_rgb(brand.secondary_color)
    
    # ============ CONSISTENT ELEMENTS ============
    
    # TOP BRAND BAR
    top_bar_h = int(canvas_size * 0.09)
    top_bar = Image.new("RGBA", (canvas_size, top_bar_h), (*primary_rgb, 235))
    bg.paste(top_bar, (0, 0), mask=top_bar)
    
    draw = ImageDraw.Draw(bg)
    
    # Company name
    brand_font = get_font(int(canvas_size * 0.034), bold=True)
    brand_x = int(canvas_size * 0.05)
    brand_y = int(top_bar_h * 0.25)
    draw.text((brand_x, brand_y), brand.company_name.upper(), font=brand_font, fill=white)
    
    # Tagline
    if brand.tagline:
        tag_font = get_font(int(canvas_size * 0.018))
        tag_w = draw.textlength(brand.tagline, font=tag_font)
        draw.text(
            (canvas_size - tag_w - int(canvas_size * 0.05), brand_y + 6),
            brand.tagline, font=tag_font, fill=(*white, 200)
        )
    
    # BOTTOM FOOTER
    footer_h = int(canvas_size * 0.06)
    footer_y = canvas_size - footer_h
    footer_bg = Image.new("RGBA", (canvas_size, footer_h), (*primary_rgb, 220))
    bg.paste(footer_bg, (0, footer_y), mask=footer_bg)
    
    footer_font = get_font(int(canvas_size * 0.022), bold=True)
    footer_w = draw.textlength(brand.website_url, font=footer_font)
    draw.text(
        ((canvas_size - footer_w) // 2, footer_y + int(footer_h * 0.28)),
        brand.website_url, font=footer_font, fill=white
    )
    
    # ============ CONTENT ZONE ============
    
    content_top = top_bar_h + int(canvas_size * 0.03)
    content_bottom = footer_y - int(canvas_size * 0.03)
    content_height = content_bottom - content_top
    
    # Semi-transparent overlay
    overlay = Image.new("RGBA", (canvas_size, content_height), (0, 0, 0, 0))
    overlay_draw = ImageDraw.Draw(overlay)
    
    if layout_strategy in ["hero_centered", "announcement"]:
        for y in range(content_height):
            alpha = int(120 * (1 - y / content_height * 0.6))
            overlay_draw.line([(0, y), (canvas_size, y)], fill=(0, 0, 0, alpha))
    else:
        overlay_draw.rectangle([(0, 0), (canvas_size, content_height)], fill=(0, 0, 0, 140))
    
    bg.paste(overlay, (0, content_top), mask=overlay)
    
    # ============ RENDER CONTENT ============
    
    pad_x = int(canvas_size * 0.07)
    text_y = content_top + int(canvas_size * 0.04)
    
    if layout_strategy == "hero_centered":
        # Large centered text
        headline_size = int(canvas_size * 0.085)
        headline_font = get_font(headline_size, bold=True)
        headline_w = draw.textlength(post.headline, font=headline_font)
        headline_x = (canvas_size - headline_w) // 2
        draw.text((headline_x, text_y), post.headline, font=headline_font, fill=white)
        text_y += int(canvas_size * 0.12)
        
        support_font = get_font(int(canvas_size * 0.032))
        wrapped = wrap(post.supporting_text, width=35)
        for line in wrapped[:2]:
            line_w = draw.textlength(line, font=support_font)
            line_x = (canvas_size - line_w) // 2
            draw.text((line_x, text_y), line, font=support_font, fill=(*white, 220))
            text_y += int(canvas_size * 0.045)
            
    elif layout_strategy == "feature_list":
        # Features with bullets
        headline_font = get_font(int(canvas_size * 0.058), bold=True)
        draw.text((pad_x, text_y), post.headline, font=headline_font, fill=white)
        text_y += int(canvas_size * 0.08)
        
        bullet_font = get_font(int(canvas_size * 0.028))
        features = post.features if post.features else [post.supporting_text[:50]]
        for i, feature in enumerate(features[:6]):
            draw.text((pad_x, text_y), f"• {feature}", font=bullet_font, fill=(*white, 220))
            text_y += int(canvas_size * 0.045)
            
    elif layout_strategy == "stats_dense":
        # Statistics grid
        headline_font = get_font(int(canvas_size * 0.07), bold=True)
        draw.text((pad_x, text_y), post.headline, font=headline_font, fill=white)
        text_y += int(canvas_size * 0.09)
        
        if post.stats:
            stat_font = get_font(int(canvas_size * 0.045), bold=True)
            stat_desc_font = get_font(int(canvas_size * 0.022))
            col_width = (canvas_size - pad_x * 2) // 2
            for i, (key, value) in enumerate(list(post.stats.items())[:4]):
                col = i % 2
                row = i // 2
                stat_x = pad_x + (col * col_width)
                stat_y = text_y + (row * int(canvas_size * 0.09))
                draw.text((stat_x, stat_y), str(value), font=stat_font, fill=accent_rgb)
                draw.text((stat_x, stat_y + int(canvas_size * 0.04)), key.replace('_', ' ').title(), 
                         font=stat_desc_font, fill=(*white, 200))
            text_y += int(canvas_size * 0.2)
    else:
        # Standard layout
        headline_font = get_font(int(canvas_size * 0.06), bold=True)
        draw.text((pad_x, text_y), post.headline, font=headline_font, fill=white)
        text_y += int(canvas_size * 0.09)
        
        support_font = get_font(int(canvas_size * 0.03))
        wrapped = wrap(post.supporting_text, width=35)
        for line in wrapped[:3]:
            draw.text((pad_x, text_y), line, font=support_font, fill=(*white, 220))
            text_y += int(canvas_size * 0.042)
    
    # CTA BUTTON
    cta_font = get_font(int(canvas_size * 0.025), bold=True)
    cta_w = int(draw.textlength(post.cta, font=cta_font)) + int(canvas_size * 0.06)
    cta_h = int(canvas_size * 0.055)
    
    cta_x = pad_x
    cta_y = content_bottom - cta_h - int(canvas_size * 0.04)
    
    if layout_strategy == "hero_centered":
        cta_x = (canvas_size - cta_w) // 2
    
    cta_rect = [cta_x, cta_y, cta_x + cta_w, cta_y + cta_h]
    draw.rounded_rectangle(cta_rect, radius=int(cta_h * 0.4), fill=accent_rgb)
    draw.text(
        (cta_x + int(canvas_size * 0.03), cta_y + int(cta_h * 0.2)),
        post.cta, font=cta_font, fill=white
    )
    
    final = bg.convert("RGB")
    final.save(out_path, "JPEG", quality=92)
    return out_path


