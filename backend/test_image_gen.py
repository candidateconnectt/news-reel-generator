class OpenRouterImageGenerator:
    @staticmethod
    async def generate(prompt: str, api_key: str, aspect_ratio: str = "1:1") -> bytes:
        loop = asyncio.get_event_loop()
        return await loop.run_in_executor(None, OpenRouterImageGenerator._sync_generate, prompt, api_key, aspect_ratio)
    
    @staticmethod
    def _sync_generate(prompt: str, api_key: str, aspect_ratio: str = "1:1") -> bytes:
        try:
            url = "https://openrouter.ai/api/v1/chat/completions"
            headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
            payload = {"model": "google/gemini-2.5-flash-image", "messages": [{"role": "user", "content": prompt}], "modalities": ["image"]}
            import requests
            response = requests.post(url, headers=headers, json=payload, timeout=120)
            response.raise_for_status()
            result = response.json()
            if result.get("choices"):
                message = result["choices"][0]["message"]
                if message.get("images"):
                    for image in message["images"]:
                        image_url = image["image_url"]["url"]
                        if image_url.startswith("data:image"):
                            return base64.b64decode(image_url.split(",")[1])
                        img_response = requests.get(image_url, timeout=60)
                        img_response.raise_for_status()
                        return img_response.content
            raise RuntimeError("No image data")
        except Exception as e:
            raise RuntimeError(f"OpenRouter error: {str(e)}")


